#!/usr/bin/env python3
"""Flatten frame.py + pb.py + agent.py into a single bringup-agent.py.

For on-device bring-up it is easier to deliver one file (one curl, or a paste)
into the guest than three. This regenerates bringup-agent.py; do not edit the
bundle by hand. The three modules have no name collisions, so flattening is just:
drop their imports, hoist one stdlib import line, and strip the `frame.`/`pb.`
module prefixes from agent.py.
"""
import pathlib

HERE = pathlib.Path(__file__).parent


def strip_imports(src: str) -> str:
    out = []
    for ln in src.splitlines():
        s = ln.strip()
        if s.startswith("import ") or s.startswith("from "):
            continue
        out.append(ln)
    return "\n".join(out).strip("\n")


def main():
    frame = strip_imports((HERE / "frame.py").read_text())
    pb = strip_imports((HERE / "pb.py").read_text())
    agent = (HERE / "agent.py").read_text().replace("frame.", "").replace("pb.", "")
    agent = strip_imports(agent)

    parts = [
        "#!/usr/bin/env python3",
        '"""Single-file bring-up build of ohmarchy-oseasy-agent. GENERATED by make-bundle.py — do not edit."""',
        "import glob, os, sys, time, struct",
        "",
        "# ===== frame.py =====",
        frame,
        "",
        "# ===== pb.py =====",
        pb,
        "",
        "# ===== agent.py =====",
        agent,
        "",
    ]
    (HERE / "bringup-agent.py").write_text("\n".join(parts))
    print("wrote bringup-agent.py")


if __name__ == "__main__":
    main()
